"""状态图：一个"行程"从生成到导出，中间会进入哪些状态、靠什么事件跳转。

为什么值得画：编辑页面上"能删、能改、能撤销、能保存"混在一起时，最容易出现
"在错误的状态里允许了错误的操作"（保存失败却显示 ✓、还没生成完就允许导出）。
状态图画出来，每个按钮该在哪个状态可点就一目了然。

布线原则：**只走横平竖直**，标签放在箭头外侧的空白带里，不压方框。
"""

from __future__ import annotations

from diagram_kit import C, Kit

W, H = 1820, 860
k = Kit(W, H, "智能旅行助手 · 行程与编辑器的状态图",
        "八个状态 · 事件驱动跳转 · 每个失败态都有确定的回退路径")

BW, BH = 214, 88
R1, R2 = 170, 430  # 两排状态的顶边
C0, C1, C2, C3 = 110, 480, 850, 1220


def state(x, y, name, lines, pair, badge=""):
    k.box(x, y, BW, BH, pair, r=10, width=2)
    k.text(x + 14, y + 10, name, k.f_body, pair[1])
    for i, s in enumerate(lines):
        k.text(x + 14, y + 36 + i * 16, s, k.f_tiny, C["muted"])
    if badge:
        k.text(x + BW - 12, y + 10, badge, k.f_tag, pair[1])
    return x, y


S0 = state(C0, R1, "空（无行程）", ["表单已填、未提交", "结果区为空"], C["input"])
S1 = state(C1, R1, "生成中", ["按钮禁用 · 进度条推进", "超时 5 分钟可取消"], C["graph"])
S2 = state(C2, R1, "只读", ["时间线 / 地图 / 预算", "可删可排序（可撤销）"], C["front"])
S3 = state(C3, R1, "编辑中", ["输入框全部可改", "撤销栈在记快照"], C["api"])
S6 = state(C1, R2, "生成失败", ["502 数据异常", "503 模型断连（可重试）"], C["err"])
S5 = state(C2, R2, "已保存", ["工具条显示「已保存」", "最近行程列表里有它"], C["out"])
S4 = state(C3, R2, "保存中", ["防抖 1.2 秒后发请求", "PUT /api/trips/{id}"], C["graph"])
S7 = state(1560, R2, "保存失败", ["磁盘不可写 / 服务未起", "工具条显示「保存失败」"], C["err"])

# 主链：空 → 生成中 → 只读 → 编辑中
k.flow([(C0 + BW, 214), (C1, 214)], "提交", color="#475569")
k.flow([(C1 + BW, 214), (C2, 214)], "生成成功", color="#047857")
k.flow([(C2 + BW, 232), (C3, 232)], "点「编辑行程」", color="#4338CA")
k.flow([(C3, 196), (C2 + BW, 196)], "放弃全部改动", color="#94A3B8")

# 编辑中 → 保存中（竖直）
k.flow([(C3 + BW / 2, R1 + BH), (C3 + BW / 2, R2)], "改动 [输入 / change]", color="#6D28D9")

# 保存中 → 已保存（向左）；保存中 → 保存失败（向右）
k.flow([(C3, 452), (C2 + BW, 452)], "保存成功", color="#047857")
k.flow([(C3 + BW, 470), (1560, 470)], "写盘失败", color="#B91C1C", dash=True)
k.flow([(1560, 500), (C3 + BW, 500)], "重试 / Ctrl+S", color="#B91C1C", dash=True)

# 已保存 → 编辑中（继续改）
k.flow(
    [(C2 + BW / 2, R2), (C2 + BW / 2, 406), (C3 + 30, 406), (C3 + 30, R1 + BH)],
    "", color="#6D28D9",
)
k.text(C2 + BW / 2 + 10, 382, "继续改", k.f_tiny, "#5B21B6")

# 生成中 → 生成失败（竖直）；重试回来
k.flow([(C1 + BW / 2, R1 + BH), (C1 + BW / 2, R2)], "", color="#B91C1C", dash=True)
k.text(C1 + BW / 2 + 10, 316, "失败 502 / 503", k.f_tiny, "#7F1D1D")
k.flow([(C1 + 46, R2), (C1 + 46, R1 + BH)], "", color="#B91C1C", dash=True)
k.right(C1 + 34, 366, "改参数重试", k.f_tiny, "#7F1D1D")

# 重新规划：只读 → 空（上方走线）
k.flow([(C2 + BW / 2, R1), (C2 + BW / 2, 132), (C0 + BW / 2, 132), (C0 + BW / 2, R1)], "重新规划", color="#94A3B8")

# 自环：只读态也能删（可撤销）
k.arrow([(C2 + 40, R1 + BH), (C2 + 40, 300), (C2 - 40, 300), (C2 - 40, R1 + BH)], "#0369A1", 2)
k.text(C2 - 130, 306, "删除 / 排序（立刻生效，可撤销）", k.f_tiny, "#0369A1")

# 初始圆点
k.d.ellipse([96 * 2, 196 * 2, 112 * 2, 212 * 2], fill="#1E293B")
k.arrow([(112, 204), (C0, 204)], "#1E293B", 2)

# ---------------------------------------------------------------- 注 --
k.box(110, 580, 720, 150, C["note"], r=10, width=2)
k.text(124, 590, "撤销 / 重做不改变状态，它只是数据的历史栈", k.f_tag, "#334155")
for i, s in enumerate([
    "· 栈里存 JSON 快照；粒度是「一次输入框焦点进出」，不是每个按键",
    "· 撤销后停在编辑中（方便接着改），并清空重做栈",
    "· 「放弃全部改动」= 回到进入编辑前的快照，同时清空撤销栈",
    "· 非编辑态也能删景点：允许，但必须可撤销 —— 否则删了就找不回来",
    "· 保存成功只认 PUT 返回 200；超时/失败一律进「保存失败」",
]):
    k.text(124, 614 + i * 20, s, k.f_tiny, C["muted"])

k.box(880, 580, 790, 150, C["err"], r=10, width=2, dash=True)
k.text(894, 590, "三个「不给用户惊喜」的约束（这才是画这张图的目的）", k.f_tag, C["err"][1])
for i, s in enumerate([
    "· 保存失败绝不显示「已保存」—— 状态由请求结果决定，不由「改过了」决定",
    "· 生成失败保留表单内容，用户不必重填 7 个字段",
    "· 工具部分失败但行程可用：进「只读」并展示 errors，不阻断使用",
    "· 每个失败态都有出口（重试 / 改参数 / 放弃），没有死路",
]):
    k.text(894, 614 + i * 20, s, k.f_tiny, "#7F1D1D")

k.footer("实心圆 = 初始；圆角框 = 状态；实线 = 正常流转；虚线 = 失败与重试；标签写在箭头外侧")

out = k.save(r"D:\PRACTICE\docs\智能旅行助手-状态图.png")
print(f"已生成: {out}  {W}x{H}")
